  const dicts = { de, tr };
  function t(lang, key, params) {
    const d = dicts[lang] || de;
    let s = d[key];
    if (s == null) s = de[key];
    if (s == null) return key;
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => {
      let v = params[k];
      if (v == null) return m;
      if (k === 'r') v = d['room.' + v] || v;
      else if (k === 'rk') v = d['role.' + v] || v;
      else if (k === 'h') v = d['h.' + v] || v;
      else if (k === 'c') v = d['card.' + v] || v;
      else if (typeof v === 'number') v = v.toLocaleString(lang === 'tr' ? 'tr-TR' : 'de-DE');
      return v;
    });
  }

